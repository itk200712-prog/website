export type Dict = (typeof dictionaries)["si"];

const LanguageContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void } | null>(null);

export function LanguageProvider({ initialLang, children }: { initialLang: Lang; children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((next: Lang) => {
    document.cookie = `lang=${next};path=/;max-age=31536000;samesite=lax`;
    setLangState(next);
  }, []);
  const value = useMemo(
    () => ({ lang, t: dictionaries[lang] as Dict, setLang }),
    [lang, setLang]
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}

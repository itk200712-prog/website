import { chromium } from "playwright";
const SITE = "https://website-blond-eta-94.vercel.app";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto(`${SITE}/signin`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
await page.fill('input[name="nic"]', "superadmin@members.mpcs.lk");
await page.fill('input[name="password"]', "Admin@123");
await page.locator('form button[type="submit"]').first().click();
await page.waitForTimeout(5000);
await page.goto(`${SITE}/admin/backup`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(4500);
await page.locator('input[placeholder*="Download"]').fill("MPCS@Backup#2026");
await page.waitForTimeout(400);
const dl = page.waitForEvent("download", { timeout: 600000 });
await page.getByRole("button", { name: /Download/i }).first().click();
const d = await dl;
await d.saveAs("/home/user/coop-web/qa-backup.zip");
console.log("downloaded:", d.suggestedFilename());
await browser.close();

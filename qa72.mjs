import { chromium } from "playwright";
const SITE = "https://website-blond-eta-94.vercel.app";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(String(e).slice(0, 140)));
page.on("console", (m) => { if (m.type() === "error" && !/favicon|404|Failed to load resource/.test(m.text())) errs.push("C:" + m.text().slice(0, 120)); });

await page.goto(SITE, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(3000);
await page.locator('button[aria-label="Live chat"]').click();
await page.waitForTimeout(800);
console.log("action buttons:", await page.evaluate(() => [...document.querySelectorAll("button")].map(b=>b.innerText.trim()).filter(t=>t && t.length<30).slice(0,18).join(" | ")));
await page.getByRole("button", { name: /Live Agent/ }).first().click();
await page.waitForTimeout(2000);
const box = page.locator('input[placeholder="Write your message…"]');
console.log("composer found:", await box.count() ? "✅" : "❌");
await box.fill("QA visitor message");
await page.locator('button').filter({ has: page.locator('svg') }).last().click().catch(()=>{});
await page.waitForTimeout(800);
// fallback: press Enter
await box.press("Enter").catch(()=>{});
await page.waitForTimeout(3000);
const body = await page.evaluate(() => document.body.innerText);
console.log("message visible in chat:", /QA visitor message/.test(body) ? "✅" : "❌");
console.log("send error shown:", /Could not send|යැවීමට බැරි/.test(body) ? "❌ YES" : "none ✅");
await page.screenshot({ path: "/home/user/view-send.png" });
console.log("JS errors:", errs.length ? errs[0] : "none ✅");
await browser.close();
